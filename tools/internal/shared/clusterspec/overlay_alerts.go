package clusterspec

// overlay_alerts.go — spec.alerting's Slack half, rendered as apl-core's own
// AplAlertSet settings CR (env/settings/alerts.yaml → `$.alerts`).
//
// The reconciler merges it KEY-LEVEL onto the apl-<env> branch
// (apl/overlay.alertsOverlayFiles), the otomi.yaml path rather than obj.yaml's
// whole-file one: the App Platform Console edits this same file (its alerts
// settings page — repeatInterval, groupInterval, the msteams block), and a
// whole-file write would blank whatever it set. LLZ owns exactly three keys:
// spec.receivers, spec.slack.channel and spec.slack.channelCrit.
//
// spec.slack.url — apl-core's x-secret — is NEVER rendered and never touched:
// apl-core would SEAL it into apl-secrets/alerts-secrets, which LLZ materialises
// from OpenBao instead (alerting.go). Writing it would put the webhook in git.

import (
	"errors"
	"slices"
	"strings"
)

// alertSetOwnedSlackKeys are the spec.slack keys LLZ asserts. Everything else
// under spec.slack (url, should apl-core ever keep it in the file) is left alone.
var alertSetOwnedSlackKeys = []string{"channel", "channelCrit"}

type alertSetDoc struct {
	Kind     string       `yaml:"kind"`
	Metadata otomiMeta    `yaml:"metadata"`
	Spec     alertSetSpec `yaml:"spec"`
}

type alertSetSpec struct {
	Receivers []string          `yaml:"receivers"`
	Slack     *alertSetSlackDoc `yaml:"slack,omitempty"`
}

type alertSetSlackDoc struct {
	Channel     string `yaml:"channel"`
	ChannelCrit string `yaml:"channelCrit"`
}

// aplAlertReceivers is the apl-core receiver list an env's effective alerting
// implies. Only slack is apl-core's; pagerduty rides LLZ's AlertmanagerConfig.
// [none] — not an absent key — when Slack is not selected, so apl-core's
// critical/default receivers route to null and cannot become a second,
// unspecified notification path behind the spec's back.
func aplAlertReceivers(a Alerting) []string {
	if a.HasReceiver("slack") {
		return []string{"slack"}
	}
	return []string{"none"}
}

// RenderAlertSetOverlay returns the per-env alerts.yaml, or "" when spec.alerting
// is not declared for the env at all (LLZ has no opinion, and apl-core's alert
// settings stand untouched).
//
// Both of apl-core's channel fields get the ONE channel: apl-core sends both its
// receivers through a single webhook URL, and a Slack-app webhook posts to the
// channel it is bound to whatever the payload says (see AlertingSlack). Writing
// a different channelCrit would describe a routing that does not exist.
func RenderAlertSetOverlay(a Alerting) string {
	if !a.Declared() {
		return ""
	}
	doc := alertSetDoc{
		Kind:     alertSetKind,
		Metadata: otomiMeta{Name: alertSetName},
		Spec:     alertSetSpec{Receivers: aplAlertReceivers(a)},
	}
	if a.HasReceiver("slack") {
		ch := a.slackChannel()
		doc.Spec.Slack = &alertSetSlackDoc{Channel: ch, ChannelCrit: ch}
	}
	return "# GENERATED by `llz render` from spec.alerting — DO NOT EDIT.\n" +
		"# apl-core's alert settings CR. The apl-overlay reconciler merges spec.receivers and\n" +
		"# spec.slack.channel/channelCrit onto env/settings/alerts.yaml; every other key there\n" +
		"# (the Console's) is left alone. The webhook URL is NOT here — see alerting.yaml.\n" +
		marshalYAML(doc)
}

// AlertSetDesired is what an alerts.yaml overlay source asserts.
type AlertSetDesired struct {
	Receivers []string
	Slack     map[string]string // owned spec.slack keys; nil when Slack is not asserted
}

// ParseAlertSetOverlay reads the desired keys out of the rendered source. A
// source with no receivers is an error: `llz render` never writes one, so it
// means the file was hand-edited into something that asserts nothing.
func ParseAlertSetOverlay(src []byte) (AlertSetDesired, error) {
	m, err := unmarshalMap(src)
	if err != nil {
		return AlertSetDesired{}, err
	}
	var d AlertSetDesired
	spec, _ := m["spec"].(map[string]any)
	if recv, ok := spec["receivers"].([]any); ok {
		for _, r := range recv {
			if s, ok := r.(string); ok {
				d.Receivers = append(d.Receivers, s)
			}
		}
	}
	if len(d.Receivers) == 0 {
		return AlertSetDesired{}, errAlertSetNoReceivers
	}
	if slack, ok := spec["slack"].(map[string]any); ok {
		d.Slack = map[string]string{}
		for _, k := range alertSetOwnedSlackKeys {
			if v, ok := slack[k].(string); ok {
				d.Slack[k] = v
			}
		}
	}
	return d, nil
}

var errAlertSetNoReceivers = errors.New("the alerts.yaml overlay source asserts no spec.receivers")

// AlertSetCRIsMergeable reports whether a target is apl-core's AplAlertSet and
// therefore safe to merge keys into. Same bar as OtomiCRIsMergeable, plus the
// kind: a file that is some other CR is not ours to edit.
func AlertSetCRIsMergeable(current []byte) bool {
	m, err := unmarshalMap(current)
	if err != nil || len(m) == 0 {
		return false
	}
	kind, _ := m["kind"].(string)
	return strings.TrimSpace(kind) == alertSetKind
}

// SetAlertSetSpec asserts the owned keys on apl-core's AplAlertSet, leaving every
// other key untouched. changed=false when they already match, so the reconciler
// does not push against a file the Console keeps rewriting.
func SetAlertSetSpec(current []byte, want AlertSetDesired) (updated []byte, changed bool, err error) {
	m, err := unmarshalMap(current)
	if err != nil {
		return nil, false, err
	}
	spec, ok := m["spec"].(map[string]any)
	if !ok {
		spec = map[string]any{}
		m["spec"] = spec
	}
	var cur []string
	if l, ok := spec["receivers"].([]any); ok {
		for _, r := range l {
			if s, ok := r.(string); ok {
				cur = append(cur, s)
			}
		}
	}
	if !slices.Equal(cur, want.Receivers) {
		l := make([]any, 0, len(want.Receivers))
		for _, r := range want.Receivers {
			l = append(l, r)
		}
		spec["receivers"] = l
		changed = true
	}
	if want.Slack != nil {
		slack, ok := spec["slack"].(map[string]any)
		if !ok {
			slack = map[string]any{}
			spec["slack"] = slack
		}
		for _, k := range alertSetOwnedSlackKeys {
			v, ok := want.Slack[k]
			if !ok {
				continue
			}
			if c, _ := slack[k].(string); c != v {
				slack[k] = v
				changed = true
			}
		}
	}
	if !changed {
		return current, false, nil
	}
	return marshalMap(m), true, nil
}
